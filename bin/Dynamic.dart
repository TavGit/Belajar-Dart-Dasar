// ini adalah tipe data dynamic & variable

// Dynamic adalah tipe data yang digunakan untuk menyimpan tipe data apapun.
// Variable adalah tempat untuk menyimpan data.

void main() {
  dynamic belajar = 17; // belajar awalnya menyimpan nilai integer, // belajar adalah nama variabel nya
  print(belajar); // Output: 17

  belajar = "Hello"; // belajar sekarang menyimpan nilai string // belajar adalah nama variabel nya
  print(belajar); // Output: Hello

  belajar = 3.14; // belajar sekarang menyimpan nilai double // belajar adalah nama variabel nya
  print(belajar); // Output: 3.14

  belajar = true; // belajar sekarang menyimpan nilai boolean // belajar adalah nama variabel nya
  print(belajar); // Output: true

}