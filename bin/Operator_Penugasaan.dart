// Operator Penugasaaan //
// Operator Penugasaan digunakan untuk memberikan nilai ke sebuah variable //

// +=
// -=
// *=
// /=
// ~/=
// %=

void main() {
  var a = 30; // Variable a bernilai 30
  var b = 10;
  var c = 100;
  var d = 50;
  var e = 20;
  var f = 1.5; // value berisi nilai double

  a += 40;
  b -= 20;
  c *= 30;
  d ~/= 10;
  e %= 3;

  f/=3; // JIKA ISI VALUE/DATAA DARI SEBUAH VARIABLE BERISI DATA DOUBLE

  print(a);
  print(b);
  print(c);
  print(d);
  print(e);
  print(f);
}
