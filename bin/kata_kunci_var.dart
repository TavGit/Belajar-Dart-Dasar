// KATA KUNCI VAR
// var adalah sebuah kata kunci, dimana jika kita menggunakan sebuah kata kunci var,
// maka kita tidak perlu menyebutkan TipeData lagi, karena si dart akan secara otomatis membaca TipeData nya.
// dan var pun bisa di ubah isi value/data nya.

void main() {
  var firstname = "Gustav";

  print(firstname);

  var angka = 99;

  print(angka);
}