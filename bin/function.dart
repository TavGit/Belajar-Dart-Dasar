// sebelum nya kita sudah menggunakan method print() untuk menampilkan tulisan di console
// untuk membuat function, kita bisa menggunakan kata kunci void, lalu diikuti dengan nama function nya, dengan kurung biasa(), dan diakhiri dengan block atau tanda kurung kurawal ().
