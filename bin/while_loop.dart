// While loop
// While loop adalah versi perulangan sederhana dibandingkan for loop
// Di While loop hanya terdapat kondisi perulangan ny saja, tanpa ada nya init statement dan post statement

void main() {
  var counter = 1;

  while (counter <= 10) { // while loop cuman ada kondisi nya doang
    print('Perulangan ke-$counter');
    counter++;
  }
}
